List<String> decomposeKorean(String name) {
  const List<String> chosung = [
    'ㄱ', 'ㄲ', 'ㄴ', 'ㄷ', 'ㄸ', 'ㄹ', 'ㅁ', 'ㅂ', 'ㅃ',
    'ㅅ', 'ㅆ', 'ㅇ', 'ㅈ', 'ㅉ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ'
  ];
  const List<String> jungsung = [
    'ㅏ', 'ㅐ', 'ㅑ', 'ㅒ', 'ㅓ', 'ㅔ', 'ㅕ', 'ㅖ', 'ㅗ', 'ㅘ',
    'ㅙ', 'ㅚ', 'ㅛ', 'ㅜ', 'ㅝ', 'ㅞ', 'ㅟ', 'ㅠ', 'ㅡ', 'ㅢ', 'ㅣ'
  ];
  const List<String> jongsung = [
    '', 'ㄱ', 'ㄲ', 'ㄳ', 'ㄴ', 'ㄵ', 'ㄶ', 'ㄷ', 'ㄹ', 'ㄺ',
    'ㄻ', 'ㄼ', 'ㄽ', 'ㄾ', 'ㄿ', 'ㅀ', 'ㅁ', 'ㅂ', 'ㅄ', 'ㅅ',
    'ㅆ', 'ㅇ', 'ㅈ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ'
  ];

  List<String> result = [];

  for (int i = 0; i < name.length; i++) {
    int code = name.codeUnitAt(i);

    if (code >= 0xAC00 && code <= 0xD7A3) {
      int unicode = code - 0xAC00;
      int cho = unicode ~/ (21 * 28);
      int jung = (unicode % (21 * 28)) ~/ 28;
      int jong = unicode % 28;

      result.add(chosung[cho]);
      result.add(jungsung[jung]);
      if (jong > 0) {
        result.add(jongsung[jong]);
      }
    }
  }

  return result;
}